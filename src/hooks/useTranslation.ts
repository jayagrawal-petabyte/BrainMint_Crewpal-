export const useTranslation = () => {
  const [lang, setLang] = useState(() => localStorage.getItem('crewpal_lang') || 'en');

  useEffect(() => {
    const handleStorageChange = () => {
      setLang(localStorage.getItem('crewpal_lang') || 'en');
    };

    window.addEventListener('storage', handleStorageChange);
    window.addEventListener('crewpal_lang_changed', handleStorageChange);

    return () => {
      window.removeEventListener('storage', handleStorageChange);
      window.removeEventListener('crewpal_lang_changed', handleStorageChange);
    };
  }, []);

  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;

  const changeLanguage = (newLang: string) => {
    localStorage.setItem('crewpal_lang', newLang);
    setLang(newLang);
    window.dispatchEvent(new Event('crewpal_lang_changed'));
  };

  return { t, lang, changeLanguage };
};
